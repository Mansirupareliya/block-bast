// Raw level data { n, paths } -> what the game plays with.
export function makeLevel(lv) {
  if (!lv) return null;
  return {
    n: lv.n,
    solution: lv.paths,
    // [[a, b], ...] — the two dots of each colour.
    dots: lv.paths.map((p) => [p[0], p[p.length - 1]]),
  };
}

// Difficulty label shown on the level select / in game.
export function tierFor(num) {
  if (num <= 10) return { name: 'BEGINNER', color: '#7CF29A' };
  if (num <= 30) return { name: 'EASY', color: '#7FD8FF' };
  if (num <= 60) return { name: 'MEDIUM', color: '#FFD24A' };
  return { name: 'ADVANCED', color: '#FF7A7A' };
}

export const isAdjacent = (n, a, b) => {
  const ra = Math.floor(a / n), ca = a % n, rb = Math.floor(b / n), cb = b % n;
  return Math.abs(ra - rb) + Math.abs(ca - cb) === 1;
};

// { cell: colour } for every dot.
export function dotMap(dots) {
  const m = new Map();
  dots.forEach(([a, b], k) => { m.set(a, k); m.set(b, k); });
  return m;
}

export const emptyPaths = (dots) => dots.map(() => []);

// A path is connected when it runs from one of its dots to the other.
export function isConnected(path, [a, b]) {
  if (path.length < 2) return false;
  const s = path[0], e = path[path.length - 1];
  return (s === a && e === b) || (s === b && e === a);
}

// Cell -> colour for everything currently drawn (dots included).
export function occupancy(n, paths, dots) {
  const occ = new Array(n * n).fill(-1);
  dots.forEach(([a, b], k) => { occ[a] = k; occ[b] = k; });
  paths.forEach((p, k) => p.forEach((cell) => { occ[cell] = k; }));
  return occ;
}

// ── Drawing ───────────────────────────────────────────────────────────────
// A drag works on a snapshot of the board taken when the finger went down
// (`base`). The line being drawn is grown/shrunk cell by cell; any other
// line it runs over is cut back to just before the crossing. Because cuts are
// always recomputed from `base`, backing the finger off restores the line
// that was cut — same feel as the classic game.

// Finger goes down on `cell`. Returns the drag state, or null if the cell
// can't start a line (an empty cell).
export function beginDrag(base, dots, n, cell) {
  const dm = dotMap(dots);
  if (dm.has(cell)) {
    // Touching a dot always starts that colour's line afresh from it.
    const k = dm.get(cell);
    return { color: k, path: [cell] };
  }
  for (let k = 0; k < base.length; k++) {
    const i = base[k].indexOf(cell);
    if (i >= 0) return { color: k, path: base[k].slice(0, i + 1) };
  }
  return null;
}

// Finger moves onto `cell`. Returns the new path for the dragged colour
// (unchanged if the move isn't allowed).
export function extendDrag(drag, dots, n, cell) {
  const { color, path } = drag;
  const last = path[path.length - 1];
  if (cell === last) return path;
  // Backtracking over its own line shortens it.
  const back = path.indexOf(cell);
  if (back >= 0) return path.slice(0, back + 1);
  if (!isAdjacent(n, last, cell)) return path;
  // A finished line doesn't grow past its second dot.
  if (isConnected(path, dots[color])) return path;
  const dm = dotMap(dots);
  if (dm.has(cell) && dm.get(cell) !== color) return path; // other colour's dot
  return [...path, cell];
}

// The board shown while dragging: `base` with the dragged line replaced and
// every other line cut where the dragged one crosses it.
export function applyDrag(base, drag) {
  const used = new Set(drag.path);
  return base.map((p, k) => {
    if (k === drag.color) return drag.path;
    const hit = p.findIndex((cell) => used.has(cell));
    return hit < 0 ? p : p.slice(0, hit);
  });
}

// Cells from `from` (exclusive) to `to` (inclusive), one grid step at a
// time — a fast swipe can skip cells between two touch events, so the board
// replays the skipped ones in order. Diagonal jumps walk the longer axis
// first, then the other.
export function walkBetween(n, from, to) {
  let r = Math.floor(from / n), c = from % n;
  const r2 = Math.floor(to / n), c2 = to % n;
  const out = [];
  while (r !== r2 || c !== c2) {
    if (Math.abs(r2 - r) >= Math.abs(c2 - c)) r += Math.sign(r2 - r);
    else c += Math.sign(c2 - c);
    out.push(r * n + c);
  }
  return out;
}

// Single-cell lines (just a dot tapped) aren't kept.
export const tidy = (paths) => paths.map((p) => (p.length < 2 ? [] : p));

// ── Progress / validation ─────────────────────────────────────────────────
export function progressOf(n, paths, dots) {
  const filled = new Set();
  dots.forEach(([a, b]) => { filled.add(a); filled.add(b); });
  paths.forEach((p) => p.forEach((cell) => filled.add(cell)));
  const connected = dots.filter((d, k) => isConnected(paths[k], d)).length;
  return { filled: filled.size, total: n * n, connected, pairs: dots.length };
}

// Full rule check used before a level is marked complete. Returns
// { ok: true } or { ok: false, reason }.
export function validateBoard(n, paths, dots) {
  const total = n * n;
  if (paths.length !== dots.length) return { ok: false, reason: 'path count' };
  const dm = dotMap(dots);
  const owner = new Array(total).fill(-1);
  let covered = 0;
  for (let k = 0; k < dots.length; k++) {
    const p = paths[k];
    // 1. Each line starts and ends at its own two dots.
    if (!isConnected(p, dots[k])) return { ok: false, reason: `colour ${k} not connected` };
    for (let i = 0; i < p.length; i++) {
      const cell = p[i];
      if (!Number.isInteger(cell) || cell < 0 || cell >= total) return { ok: false, reason: 'off grid' };
      // 2. Continuous, horizontal/vertical steps only.
      if (i > 0 && !isAdjacent(n, p[i - 1], cell)) return { ok: false, reason: `colour ${k} jumps` };
      // 3. Never through another colour's dot.
      if (dm.has(cell) && dm.get(cell) !== k) return { ok: false, reason: `colour ${k} crosses a dot` };
      // 4. No two lines (or one line twice) in the same cell.
      if (owner[cell] !== -1) return { ok: false, reason: `overlap at ${cell}` };
      owner[cell] = k;
      covered += 1;
    }
  }
  // 5. Every cell filled: covered count must equal rows × columns.
  if (covered !== total) return { ok: false, reason: `${total - covered} empty cells` };
  return { ok: true };
}

// ── Hint ──────────────────────────────────────────────────────────────────
// Lays down one colour's solution line (first a colour that isn't connected
// yet, otherwise one the player connected differently), cutting anything in
// its way. Returns { paths, color } or null when the board already matches.
export function applyHint(paths, level) {
  const { solution, dots } = level;
  const same = (a, b) => a.length === b.length
    && (a.every((x, i) => x === b[i]) || a.every((x, i) => x === b[b.length - 1 - i]));
  const order = [
    ...dots.map((d, k) => k).filter((k) => !isConnected(paths[k], dots[k])),
    ...dots.map((d, k) => k).filter((k) => isConnected(paths[k], dots[k]) && !same(paths[k], solution[k])),
  ];
  if (!order.length) return null;
  const k = order[0];
  return { color: k, paths: tidy(applyDrag(paths, { color: k, path: solution[k].slice() })) };
}
