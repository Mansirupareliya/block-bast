// Color Connect — pure game logic (no React / React Native imports, so the
// level generator and tests in scripts/ can run it under plain Node).
//
// Cells are numbered r * n + c. A level is { n, paths } where `paths` is the
// stored solution: one array of cells per colour, ordered from one endpoint
// to the other. Together the solution paths cover every cell exactly once,
// so every level is solvable with a full board by construction (and
// scripts/testColorConnect.mjs re-checks all of them).
//
// The player's board uses the same shape: `paths[k]` is the line drawn for
// colour k, always starting at one of colour k's two dots ([] = not drawn).
// The level data itself lives in colorConnectLevels.js (generated by
// scripts/generateColorConnectLevels.mjs).

// Vivid colours that stay distinct from each other and readable on the dark
// board. Index = colour id.
